"""Insert all indexed 50ohm course links as HamRadioTrainer appendix hints."""
import html
import json
from pathlib import Path
from urllib.parse import urlsplit
import xml.etree.ElementTree as ET

PREFIX = '50ohm.de – Kurskapitel'


def add_50ohm_hints(appendix_xml, catalog_xml, index_path='50ohm_links.json'):
    payload=json.loads(Path(index_path).read_text(encoding='utf-8-sig'))
    if payload.get('schema_version')!=1 or not isinstance(payload.get('questions'),dict):
        raise ValueError('Unbekanntes 50ohm-Linkindexformat.')
    if payload.get('errors'):
        raise ValueError('Der 50ohm-Index enthaelt Abruffehler. Bitte Indexlauf pruefen.')
    index=payload['questions']
    catalog=ET.fromstring(catalog_xml)
    root=ET.fromstring(appendix_xml)
    if root.tag!='catalogappendix':raise ValueError('Erwartet <catalogappendix>.')
    # Idempotent: only replace hints generated by this helper.
    for parent in root.iter():
        for child in list(parent):
            if child.tag=='hint' and (child.text or '').startswith(PREFIX):
                parent.remove(child)
    count=links_count=0;missing=[]
    for question in catalog.findall('.//question'):
        qid=question.get('id','')
        entries=index.get(qid,[])
        unique={}
        for entry in entries:
            url=entry['url'];p=urlsplit(url)
            if p.scheme!='https' or p.netloc!='50ohm.de' or not p.path.endswith('.html'):
                raise ValueError('Unerwartete Link-URL: '+url)
            unique.setdefault(url,entry)
        if not unique:
            missing.append(qid);continue
        items=[]
        for url,entry in sorted(unique.items()):
            label=f"{entry.get('title',qid)} (Kursvariante {entry.get('variant','?')})"
            items.append('<li><a href="'+html.escape(url,quote=True)+'">'+html.escape(label)+'</a></li>')
        hint=ET.SubElement(root,'hint',{'question':qid})
        hint.text=PREFIX+':<ul>'+''.join(items)+'</ul>'
        count+=1;links_count+=len(unique)
    ET.indent(root,space='  ')
    print(f'50ohm: Hinweise fuer {count} Fragen, {links_count} Links, {len(missing)} Fragen ohne Fundstelle.')
    return '<?xml version="1.0" encoding="UTF-8"?>\n'+ET.tostring(root,encoding='unicode')+'\n'
